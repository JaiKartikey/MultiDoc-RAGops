# ===================================Retrieval Evaluation ========================================


# Context Recall.: Did we retrieve the information needed to answer?
# Context Precision. Of the chunks we retrieved, how many were actually relevant?


def context_Recall(
    retrieved_content:str,
    ground_truth:str,
)->float:

    ground_truth_words = set(
        ground_truth.lower().strip().split()
    )

    retrieved_words= set(
        retrieved_content.lower().split()
    )

    if not ground_truth_words:
        return 0.0

    matched_words =ground_truth_words.intersection(
        retrieved_words
    )

    return len(matched_words)/ len(ground_truth_words)


def context_Precision(
    retrieved_chunks: list[str],
    ground_truth:str
)->float:

    if not retrieved_chunks:
        return 0.0

    ground_truth_words = set(
        ground_truth.lower().strip().split()
    )

    relevant_chunks:int =0

    for chunk in retrieved_chunks:

        chunk_words = set(
            chunk.lower().strip().split()
        )

        overlap = chunk_words.intersection(
            ground_truth_words
        )

        if overlap:
            relevant_chunks+=1

    return relevant_chunks/len(retrieved_chunks)

    
