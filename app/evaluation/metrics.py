# LLM as the judge

from openai import OpenAI
from app.core.config import settings

client = OpenAI(
    api_key=settings.gemini_api_key,
    base_url=settings.gemini_api_base_url
)


def faithfulness(
    context,
    answer
)->float:

    prompt = f"""
    You are evaluating the faithfulness of a RAG answer.

    Your job is to determine whether the answer
    is supported by the provided context.

    Context:
    {context}

    Answer:
    {answer}

    Give a score between 0 and 1.

    1.0 = completely supported by the context
    0.0 = completely unsupported by the context

    Return ONLY the numerical score.
    """

    response= client.chat.completions.create(
        model=settings.llm_model,
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature =0
    )

    result = response.choices[0].message.content.strip()

    try:
        score = float(result)
    except ValueError:
        return 0.0

    return max(0.0, min(score, 1.0))



